def get_main_system_prompt(eval_mode: bool = False) -> str:
    if eval_mode:
        return MAIN_AGENT_SYSTEM_PROMPT_EVAL
    return MAIN_AGENT_SYSTEM_PROMPT

def get_system_prompt_with_profile(
    username: str,
    profile: str,
    summary: str = "",
    eval_mode: bool = False,
) -> str:
    parts = [get_main_system_prompt(eval_mode=eval_mode), f"\n【当前用户】{username}"]
    if profile:
        parts.append(f"【用户画像 Profile】\n{profile}")
    else:
        parts.append("（这位用户暂时还没有画像记录。）")
    if summary:
        parts.append(f"\n[Summary]\n{summary}\n[/Summary]")
    return "\n\n".join(parts)
